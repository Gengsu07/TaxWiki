#!/usr/bin/env python3
"""
make-dataset.py — mine raw/ + wiki/ into Unsloth-ready fine-tuning datasets.

Design goals:
- Incremental: re-run after every ingest batch. Sample identity and the
  train/eval split are deterministic (hashed per source), so re-runs only
  append new samples and git diffs stay minimal.
- Gold data only: pages with status "stable" or "review" are used by default.
  Draft pages are excluded (they would teach the model format errors).
- No external deps: stdlib only (PyYAML is used if available, otherwise a
  minimal frontmatter parser handles this wiki's fixed format).

Outputs (all under dataset/):
  task-train.jsonl / task-eval.jsonl  — wiki-authoring task demonstrations
  qa-train.jsonl   / qa-eval.jsonl    — grounded Q&A pairs (merged from qa-raw/)
  manifest.json                        — run summary + sample accounting

Task types emitted per wiki page (one sample = one scoped subtask):
  1. page-write : full source -> full wiki page   (only if source <= MAX_SOURCE_CHARS)
  2. summarize  : page body -> its **Summary** line
  3. classify   : title+summary -> chapter name

QA pairs are NOT invented here. They accumulate in dataset/qa-raw/<source-slug>.jsonl
during ingest (generated by the strong model). This script merges and dedupes them.

Usage:
    python tools/make-dataset.py
    python tools/make-dataset.py --include-drafts   # also use status: draft pages
"""

import hashlib
import json
import re
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW_DIR = ROOT / "raw"
WIKI_DIR = ROOT / "wiki"
DATASET_DIR = ROOT / "dataset"
QA_RAW_DIR = DATASET_DIR / "qa-raw"
EXAMPLES_DIR = DATASET_DIR / "examples"

MAX_SOURCE_CHARS = 10_000   # page-write samples only when the source fits training context
MAX_PAGE_CHARS = 6_000      # summarize samples truncate the page body to this
EVAL_THRESHOLD = 0x1A       # sha1(slug)[0] < 0x1A  -> ~10% eval, deterministic
STATUS_FILTER = {"stable", "review"}

SKIP_FILES = {
    "index.md", "log.md", "_learning-path.md", "README.md",
}

TASK_SYSTEM = (
    "Kamu adalah AI pemelihara knowledge base \"Wiki Pajak Indonesia\" yang mengikuti "
    "pola LLM Wiki. Kamu menulis halaman wiki Markdown dalam Bahasa Indonesia formal. "
    "Setiap halaman wajib memiliki YAML frontmatter dengan field: title, tags (array, "
    "elemen pertama 'concept' untuk halaman konsep atau 'summary'/'source' untuk halaman "
    "sumber), date (YYYY-MM-DD), sources (array nama file sumber), status "
    "(draft/review/stable), dan chapter untuk halaman konsep. Struktur isi: baris "
    "'# Judul', lalu baris '**Summary**: ...', lalu pembatas '---', lalu konten dengan "
    "heading yang jelas, diakhiri bagian '## Related pages' berisi [[wiki-link]]. "
    "Klaim faktual dirujuk dengan format (source: nama-file.md)."
)

QA_SYSTEM = (
    "Kamu adalah asisten Wiki Pajak Indonesia. Jawab pertanyaan HANYA berdasarkan "
    "konteks yang diberikan. Kutip sumber dengan format (source: nama-file.md). "
    "Jika konteks tidak memuat jawabannya, katakan dengan jujur bahwa kamu tidak tahu."
)


# --------------------------------------------------------------------------- #
# Frontmatter parsing (minimal, stdlib-only fallback)
# --------------------------------------------------------------------------- #

def parse_frontmatter(text: str):
    """Return (meta: dict, body: str). Handles this wiki's flat YAML frontmatter."""
    if not text.startswith("---"):
        return {}, text
    end = text.find("\n---", 3)
    if end == -1:
        return {}, text
    meta_block = text[3:end]
    body = text[end + 4:].lstrip("\n")
    meta = {}
    for line in meta_block.splitlines():
        line = line.strip()
        if not line or ":" not in line:
            continue
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("[") and value.endswith("]"):
            items = [v.strip().strip("\"'") for v in value[1:-1].split(",") if v.strip()]
            meta[key.strip()] = items
        else:
            meta[key.strip()] = value.strip("\"'")
    return meta, body


def extract_summary(body: str):
    m = re.search(r"\*\*Summary\*\*:\s*(.+)", body)
    return m.group(1).strip() if m else None


# --------------------------------------------------------------------------- #
# Scanning
# --------------------------------------------------------------------------- #

def find_sources():
    """All ingestible sources under raw/, keyed by basename -> content."""
    sources = {}  # basename -> (relpath, text)
    for p in sorted(RAW_DIR.rglob("*")):
        if p.is_dir() or p.name.startswith("."):
            continue
        if p.suffix.lower() not in {".md", ".txt"}:
            continue
        try:
            sources[p.name] = (str(p.relative_to(ROOT)), p.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, OSError):
            continue
    return sources


def find_wiki_pages():
    """All authored wiki pages with valid frontmatter. Returns list of dicts."""
    pages = []
    for p in sorted(WIKI_DIR.rglob("*.md")):
        if p.name in SKIP_FILES or "_learning-path" in p.name:
            continue
        try:
            text = p.read_text(encoding="utf-8")
        except OSError:
            continue
        meta, body = parse_frontmatter(text)
        if not meta.get("title") or not meta.get("status"):
            continue
        pages.append({
            "path": str(p.relative_to(ROOT)),
            "slug": str(p.relative_to(WIKI_DIR)).replace("\\", "/")[:-3],
            "meta": meta,
            "body": body,
        })
    return pages


def available_chapters():
    chapters = ["foundations", "cross-cutting"]
    for d in sorted((WIKI_DIR / "concept").iterdir()):
        if d.is_dir() and not d.name.startswith("."):
            chapters.append(d.name)
    return sorted(set(chapters))


# --------------------------------------------------------------------------- #
# Split (deterministic, stable across incremental re-runs)
# --------------------------------------------------------------------------- #

def is_eval(slug: str):
    return hashlib.sha1(slug.encode("utf-8")).digest()[0] < EVAL_THRESHOLD


# --------------------------------------------------------------------------- #
# Task sample generators (one sample = one scoped subtask)
# --------------------------------------------------------------------------- #

def slugify(text: str):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:60] or "page"


def gen_page_write(page, sources):
    """full source -> full wiki page (only for short sources)."""
    tags = page["meta"].get("tags", [])
    kind = "halaman konsep" if "concept" in tags else "halaman ringkasan sumber"
    chapter = page["meta"].get("chapter")
    chapter_suffix = f" untuk chapter '{chapter}'" if chapter else ""
    out = []
    for src_name in page["meta"].get("sources", []):
        hit = sources.get(src_name)
        if not hit:
            continue
        relpath, text = hit
        if len(text) > MAX_SOURCE_CHARS:
            continue
        human = (
            f"Sumber: {relpath}\n\n{text}\n\n"
            f"Tugas: tulis {kind} '{page['meta']['title']}'{chapter_suffix} "
            "berdasarkan sumber di atas. Ikuti format frontmatter dan struktur "
            "halaman wiki persis seperti yang dijelaskan."
        )
        gpt = page["body"].strip()
        out.append({"conversations": [
            {"from": "system", "value": TASK_SYSTEM},
            {"from": "human", "value": human},
            {"from": "gpt", "value": gpt},
        ]})
    return out


def gen_summarize(page):
    """page body -> one-sentence Summary line."""
    summary = extract_summary(page["body"])
    if not summary:
        return []
    body = page["body"]
    if len(body) > MAX_PAGE_CHARS:
        body = body[:MAX_PAGE_CHARS] + "\n[...terpotong...]"
    human = (
        f"Berikut isi halaman wiki:\n\n{body}\n\n"
        "Tugas: tulis satu baris Summary untuk halaman ini dengan format persis "
        "'**Summary**: <satu sampai dua kalimat>'."
    )
    return [{"conversations": [
        {"from": "system", "value": TASK_SYSTEM},
        {"from": "human", "value": human},
        {"from": "gpt", "value": f"**Summary**: {summary}"},
    ]}]


def gen_classify(page, chapters):
    """title + summary -> chapter name."""
    chapter = page["meta"].get("chapter")
    summary = extract_summary(page["body"])
    if not chapter or not summary:
        return []
    human = (
        f"Judul halaman: {page['meta']['title']}\n"
        f"Ringkasan: {summary}\n\n"
        f"Chapter yang tersedia: {', '.join(chapters)}\n\n"
        "Tugas: pilih satu chapter yang paling tepat untuk halaman ini. "
        "Jawab hanya dengan nama chapter, tanpa penjelasan."
    )
    return [{"conversations": [
        {"from": "system", "value": TASK_SYSTEM},
        {"from": "human", "value": human},
        {"from": "gpt", "value": chapter},
    ]}]


# --------------------------------------------------------------------------- #
# QA merge (from qa-raw/, accumulated during ingest)
# --------------------------------------------------------------------------- #

def merge_qa():
    """Merge dataset/qa-raw/*.jsonl into deduped QA samples with stable split."""
    seen = set()
    train, eval_ = [], []
    if not QA_RAW_DIR.exists():
        return train, eval_
    for f in sorted(QA_RAW_DIR.glob("*.jsonl")):
        slug = f.stem
        try:
            for line in f.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line:
                    continue
                rec = json.loads(line)
                convs = rec.get("conversations")
                if not convs or len(convs) < 2:
                    continue
                key = hashlib.sha1(convs[-2].get("value", "").encode("utf-8")).hexdigest()
                if key in seen:
                    continue
                seen.add(key)
                (eval_ if is_eval(slug) else train).append(rec)
        except (json.JSONDecodeError, OSError) as e:
            print(f"  ! qa-raw/{f.name}: skipped ({e})")
    return train, eval_


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #

def main():
    include_drafts = "--include-drafts" in sys.argv
    status_filter = STATUS_FILTER | ({"draft"} if include_drafts else set())

    sources = find_sources()
    pages = [p for p in find_wiki_pages() if p["meta"].get("status") in status_filter]
    chapters = available_chapters()

    task_train, task_eval = [], []
    skipped = {"no_source_found": 0, "source_too_long": 0, "no_summary": 0,
               "no_chapter": 0, "draft_excluded": 0}

    for p in find_wiki_pages():
        if p["meta"].get("status") not in status_filter:
            skipped["draft_excluded"] += 1
            continue
        for sample in gen_page_write(p, sources):
            (task_eval if is_eval(p["slug"]) else task_train).append(sample)
        for sample in gen_summarize(p):
            (task_eval if is_eval(p["slug"]) else task_train).append(sample)
        for sample in gen_classify(p, chapters):
            (task_eval if is_eval(p["slug"]) else task_train).append(sample)
        # accounting for skipped page-write sources
        for src in p["meta"].get("sources", []):
            if src not in sources:
                skipped["no_source_found"] += 1
            elif len(sources[src][1]) > MAX_SOURCE_CHARS:
                skipped["source_too_long"] += 1
        if not extract_summary(p["body"]):
            skipped["no_summary"] += 1
        if not p["meta"].get("chapter"):
            skipped["no_chapter"] += 1

    qa_train, qa_eval = merge_qa()

    DATASET_DIR.mkdir(exist_ok=True)
    files = {
        "task-train.jsonl": task_train, "task-eval.jsonl": task_eval,
        "qa-train.jsonl": qa_train, "qa-eval.jsonl": qa_eval,
    }
    for name, rows in files.items():
        (DATASET_DIR / name).write_text(
            "\n".join(json.dumps(r, ensure_ascii=False) for r in rows) + ("\n" if rows else ""),
            encoding="utf-8",
        )

    manifest = {
        "generated_at": time.strftime("%Y-%m-%d %H:%M:%S"),
        "include_drafts": include_drafts,
        "sources_scanned": len(sources),
        "pages_scanned": len(pages),
        "chapters": chapters,
        "counts": {k: len(v) for k, v in files.items()},
        "skipped": skipped,
    }
    (DATASET_DIR / "manifest.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8"
    )

    print(f"sources: {len(sources)}  pages (in scope): {len(pages)}")
    print(f"task samples: train={len(task_train)} eval={len(task_eval)}")
    print(f"qa samples:   train={len(qa_train)} eval={len(qa_eval)}")
    if not task_train and not task_eval and not qa_train and not qa_eval:
        print("\nNo training data yet — ingest sources first (pages must reach")
        print("status 'stable'/'review'). See dataset/README.md and dataset/examples/.")
    print(f"\nwrote: {DATASET_DIR}")


if __name__ == "__main__":
    main()
